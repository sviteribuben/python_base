# Статические и классовые методы — это инструменты, которые позволяют расширить
# функциональность классов без привязки к экземплярам.
# В Python 3.15 они остаются ключевым элементом ООП.

# Основные концепции
# 1. @staticmethod
# Статический метод — это метод класса, который не имеет доступа
# к экземпляру класса (self) или классу (cls). Он работает как обычная функция,
# но находится внутри класса.
# Преимущество: позволяет создавать полезные функции, которые не зависят
# от состояния экземпляра класса.

# Когда использовать:
# Когда нужно написать функцию, которая выполняет операцию, не требующую доступа к экземпляру.
# Для удобного доступа к функциям из разных частей кода.

# 2. @classmethod
# @classmethod — это метод класса, который имеет доступ к классу (с помощью аргумента cls).
# Он может быть использован для работы с классом, а не с экземплярами.
# Преимущество: позволяет создавать экземпляры класса или выполнять операции, связанные с классом.

# Когда использовать:

# Когда нужно создавать экземпляры класса с разными параметрами.
# Для инициализации класса или работы с классами на уровне класса (например, для создания экземпляров с разными настройками).
# Примеры типизированного кода

# 1. @staticmethod
#  @staticmethod не зависит от экземпляра класса.
# Например, функция для вычисления площади круга:

from typing import Any, Type, Union, Dict
import json
import math


class Geometry:
    @staticmethod
    def calculate_circle_area(radius: float) -> float:
        """Вычисляет площадь круга по радиусу."""
        return math.pi * radius**2


# Использование статического метода
print(Geometry.calculate_circle_area(5))


# 2. @classmethod
# Классовой метод позволяет создавать экземпляры класса с разными параметрами.
# Например, класс для работы с настройками:


class Settings:
    @classmethod
    def create_from_dict(cls, config: Dict[str, Any]) -> Settings:
        """Создает экземпляр Settings из словаря конфигурации."""
        return cls(**config)

    def __init__(self, key: str, value: Any):
        self.key = key
        self.value = value


# Использование классового метода
config = {"key": "theme", "value": "dark"}
settings = Settings.create_from_dict(config)
print(settings.key)  # "theme"
print(settings.value)  # "dark"

# 3. Разница между staticmethod и classmethod


class MathUtils:
    @staticmethod
    def add(a: int, b: int) -> int:
        return a + b

    @classmethod
    def multiply_by_two(cls, x: int) -> int:
        return cls._multiply(x, 2)  # Внутренняя функция для упрощения

    @staticmethod
    def _multiply(a: int, b: int) -> int:
        return a * b


print(MathUtils.add(3, 4))  # 7
print(MathUtils.multiply_by_two(5))  # 10

# Ключевое отличие:

# @staticmethod — это функция, которая не зависит от экземпляра класса.
# @classmethod — это метод, который имеет доступ к классу (с помощью cls).
# Когда использовать статические и классовые методы?
# 1. Статический метод
# Когда нужно создать функцию, которая не зависит от экземпляра класса.
# Пример: математические функции, конвертеры единиц измерения.
# 2. Классовой метод
# Когда нужно создавать экземпляры класса с разными настройками.
# Пример: инициализация класса из конфигурационного файла или словаря.
# 3. Общая рекомендация
# Используйте @staticmethod, если функция не связана с экземпляром класса.
# Используйте @classmethod, если нужно работать с классом (например, для создания экземпляров).


# Примеры реального применения
# 1. Статический метод для форматирования текста


class TextFormatter:
    @staticmethod
    def capitalize_first_letter(text: str) -> str:
        """Превращает первую букву строки в заглавную."""
        return text[0].upper() + text[1:]


print(TextFormatter.capitalize_first_letter("hello"))  # "Hello"

# 2. Класс метод для управления конфигурацией


class Config:
    @classmethod
    def load_from_file(cls, filename: str) -> Config:
        """Загружает конфигурацию из файла."""
        with open(filename, "r") as f:
            config = json.load(f)
        return cls(**config)


# Использование
config = Config.load_from_file("settings.json")

