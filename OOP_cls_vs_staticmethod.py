# @classmethod — это методы, которые имеют доступ к классу и могут создавать экземпляры.
# Используйте их так, чтобы код был читаемым, типизированным и структурированным.
# В Python 3.15 эти методы остаются актуальными и продолжают играть ключевую роль в разработке.
